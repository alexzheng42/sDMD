void InitializeCG(void) {
    if (strcmp(CG.type[1], "alphaC") == 0) {
        CG.totalNum = numofRes;
        CG.list = (int *)calloc(numofRes + 1, sizeof(int));
        CG.thisCG = (struct CGStr *)calloc(numofRes + 1, sizeof(struct CGStr));
        
        //all the atoms in the residue are mapped on the alpha-C
        for (int i = 1; i <= numofRes; i ++) {
            for (int n = residue[i].startAtomNum; n <= residue[i].endAtomNum; n ++) {
                if (strcmp(atom[n].property->name, "CA") == 0) {
                    CG.list[i]         = n;
                    CG.thisCG[i].start = residue[i].startAtomNum;
                    CG.thisCG[i].end   = residue[i].endAtomNum;
                    FindStrInList(atom[n].property->extraProperty, "CG", 1);
                    break;
                }
            }
        }
    } else if (strcmp(CG.type[1], "residue") == 0) {
        CG.totalNum = numofRes;
        CG.list = (int *)calloc(numofRes + 1, sizeof(int));
        CG.thisCG = (struct CGStr *)calloc(numofRes + 1, sizeof(struct CGStr));
        
        //all the atoms in the residue share the same Chi of its residue
        for (int i = 1; i <= numofRes; i ++) {
            for (int n = residue[i].startAtomNum; n <= residue[i].endAtomNum; n ++) {
                if (strcmp(atom[n].property->name, "CA") == 0) {
                    CG.list[i]         = n;
                    CG.thisCG[i].start = residue[i].startAtomNum;
                    CG.thisCG[i].end   = residue[i].endAtomNum;
                }
                FindStrInList(atom[n].property->extraProperty, "CG", 1);
            }
        }
    } else {
        printf("!!ERROR!!: the CG type is invalid. %s:%i\n", __FILE__, __LINE__);
        exit(EXIT_FAILURE);
    }
    
	InitializeCGPotential();
    return;
}


void InitializeCGPotential(void) {
    char buffer[PATH_LEN], statement[128];
    FILE *input_file;
    CGMatrix.CGBead = (struct CGBeadStr *)calloc(FFInfo.group[0].val[0] + 1, sizeof(struct CGBeadStr));
    
    if (strcmp(CG.type[1], "alphaC") == 0 ||
        strcmp(CG.type[1], "residue"  ) == 0) {
        
        //parameter file generated by
        //http://www.mmtsb.org/webservices/gomodel.html
        sprintf(buffer, "%s/Library_Go/CGParameterTable.txt", datadir);
        input_file = fopen(buffer, "r");
        if (input_file == NULL) {
            printf("!!ERROR!!: cannot find CGParameterTable.txt file in %s/Library_Go/!\n", datadir);
            printf("           please check your directory!\n");
            exit(EXIT_FAILURE);
        }
        
        while (fgets(statement, sizeof(statement), input_file)) {
            if (statement[0] == '#') {
                continue;
            }
            
            int pos = 0;
            sscanf(statement, "%s%n", buffer, &pos);
            if (strcmp(buffer, "THETA") == 0) {
                sscanf(statement + pos, "%lf%lf%lf%lf%lf",
                       &CGMatrix.theta[0],
                       &CGMatrix.theta[1],
                       &CGMatrix.theta[2],
                       &CGMatrix.theta[3],
                       &CGMatrix.theta[4]);
            } else {
                int ResIndex = FindResIndex(buffer);
                sscanf(statement + pos, "%lf%lf%lf%lf",
                       &CGMatrix.CGBead[ResIndex].chi,
                       &CGMatrix.CGBead[ResIndex].epsilon,
                       &CGMatrix.CGBead[ResIndex].sigma,
                       &CGMatrix.CGBead[ResIndex].delta);
            }
        }
        fclose(input_file);
        
        CreateCGPotentialTable();
        ReadCGPotTable();
        
#ifdef CG_DEBUG
        PrintStepPotFun();
#endif
    }
    
    return;
}


void CreateCGPotentialTable(void) {
    char buffer[PATH_LEN];
    char *sur_type[3] = {"PHO", "PHI", "RPH"}; //these are corresponding to the surface type, see FindResIndex() in Model.c.
    int step, num_sur = 3, flag;
    double minPDis, minDis;
    double gap[3] = {1.0, 2.0, 0.01}; //0: potential gap; 1: distance gap; 2: step length
    double dis, disPot[128][2] = {0};
    FILE *outputPoten;
    
#ifdef CG_DEBUG
    PrintPotCur_Res();
    PrintPotCur_Pep();
#endif
    
    sprintf(buffer, "%s/Library_Go/CGPotenTable.txt", datadir);
    outputPoten = fopen(buffer, "w");
    
    for (int i = 0; i < num_sur; i ++) {
        for (int n = 1; n <= FFInfo.group[0].val[0]; n ++) {
            
			//the initial sigma = 0, this is to void the unavailable types
            if (CGMatrix.CGBead[n].sigma <= 0 ||
                FindResIndex(sur_type[0]) == n ||
                FindResIndex(sur_type[1]) == n ||
                FindResIndex(sur_type[2]) == n) {
                continue;
            }
            
            //the minimum distance
            minDis  = FindMaxPotDis(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                    CGMatrix.CGBead[n], MAX_P);
            //the distance at which the potenial has the minimum
            minPDis = FindMinPotDis(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                    CGMatrix.CGBead[n], 0);
            
            fprintf(outputPoten, "%5s %5s ", sur_type[i], FFInfo.group[n].name);
            fprintf(outputPoten, "%10.6lf ", minDis);
            
            step = 0; flag = 1;
            dis = minDis + gap[2];
            disPot[step][0] = dis;
            disPot[step++][1] = CalculateSurPoten(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                                  CGMatrix.CGBead[n], dis);
            
            //calculate the discretized points of potential
            while (dis <= MAX_R) {
                dis += gap[2];
                
                if (step == 128) {
                    printf("!!ERROR!!: too many steps! please increase the step gap. %s:%i\n", __FILE__, __LINE__);
                    exit(EXIT_FAILURE);
                }
                
                disPot[step][0] = dis;
                disPot[step][1] = CalculateSurPoten(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                                    CGMatrix.CGBead[n], dis);
                
                if (flag && fabs(disPot[step][0] - minPDis) < gap[2]) { //only do this once
                    disPot[step][0] = minPDis;
                    disPot[step][1] = CalculateSurPoten(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                                        CGMatrix.CGBead[n], minPDis);
                    if (disPot[step][0] - disPot[step - 1][0] > gap[1] * 0.1 ||
                        fabs(disPot[step][1] - disPot[step - 1][1]) > gap[0] * 0.1) {
                        step ++;
                    }
                    flag = 0;
                } else if (disPot[step][0] - disPot[step - 1][0] > gap[1] ||
                    fabs(disPot[step][1] - disPot[step - 1][1]) > gap[0]) {
                    step ++;
                }
            }
            
#ifdef CG_DEBUG
            PrintDisPot(disPot, step, sur_type[i], n);
#endif
            
            int stepRecord = step; step = 0;
            while (++step < stepRecord) {
                fprintf(outputPoten, "%10.6lf %10.6lf ", (disPot[step - 1][0] + disPot[step][0]) * 0.5, (disPot[step - 1][1] - disPot[step][1]));
            }
            fprintf(outputPoten, "%10.6lf %10.6lf\n", disPot[step - 1][0], disPot[step - 1][1]);
        }
    }
    
    fclose(outputPoten);
    return;
}


void PrintPotCur_Res(void) {
    FILE *potCurFile;
    char name[PATH_LEN];
    char *sur_type[3] = {"PHO", "PHI", "RPH"}; //these are corresponding to the surface type, see FindResIndex() in Model.c.
    int num_sur = 3;
    double dis, gap = 0.02;
    double poten = 0;

    for (int i = 0; i < num_sur; i ++) {
        for (int n = 1; n <= FFInfo.group[0].val[0]; n ++) {
            
            if (CGMatrix.CGBead[n].sigma <= 0 ||
                FindResIndex(sur_type[0]) == n ||
                FindResIndex(sur_type[1]) == n ||
                FindResIndex(sur_type[2]) == n) {
                continue;
            }
            
            sprintf(name, "%s/%s-%s.txt", savedir, sur_type[i], FFInfo.group[n].name);
            potCurFile = fopen(name, "w");
            
            dis = FindMaxPotDis(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                CGMatrix.CGBead[n], 0.6);
            while (dis < MAX_R) {
                poten = CalculateSurPoten(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                          CGMatrix.CGBead[n], dis);
                fprintf(potCurFile, "%8.4lf  %8.4lf\n", dis, poten);
                
                dis += gap;
            }
            fprintf(potCurFile, "\n");
            fclose(potCurFile);
        }
    }
    return;
}


void PrintPotCur_Pep(void) {
    FILE *potCurFile;
    char name[PATH_LEN];
    char *sur_type[3] = {"PHO", "PHI", "RPH"}; //these are corresponding to the surface type, see FindResIndex() in Model.c.
    int num_sur = 3, dim = 2;
    double dis, shift, gap = 0.1;
    double poten = 0;
    
    for (int i = 0; i < num_sur; i ++) {
        sprintf(name, "%s/%s-Pep.txt", savedir, sur_type[i]);
        potCurFile = fopen(name, "w");
        
        dis   = 2.0;
        shift = FindMinDisDimen(dim); //on y-axis

        while (dis < MAX_R) {
            poten = 0;
            for (int n = 1; n <= numofRes; n ++) {
                
                int ResHead = residue[n].startAtomNum;
                int ResEnd  = residue[n].endAtomNum;
                
                for (int j = ResHead; j <= ResEnd; j ++) {
                    if (FindStrInList(atom[j].property->extraProperty, "CG", 0)) {
                        poten += CalculateSurPoten(CGMatrix.CGBead[FindResIndex(sur_type[i])],
                                                   CGMatrix.CGBead[residue[n].type],
                                                   dis + atom[j].dynamic->coordinate[dim] - shift);
                    }
                }
            }
            
            if (poten < MAX_P) fprintf(potCurFile, "%8.4lf  %8.4lf\n", dis, poten);
            dis += gap;
        }
        fprintf(potCurFile, "\n");
        fclose(potCurFile);
    }
    return;
}


double FindMinDisDimen(int dim) {
    double dis = INFINIT;
    
    for (int n = 1; n <= numofRes; n ++) {
        int ResHead = residue[n].startAtomNum;
        int ResEnd  = residue[n].endAtomNum;
        
        for (int i = ResHead; i <= ResEnd; i ++) {
            if (FindStrInList(atom[i].property->extraProperty, "CG", 0)) {
                if (dis > atom[i].dynamic->coordinate[dim]) {
                    dis = atom[i].dynamic->coordinate[dim];
                }
            }
        }
    }
    
    return dis;
}


